const strip = s => String(s || '')
  .replace(/[市]$/, '')
  .replace(/(自治州|地区|盟|特别行政区)$/, '');

// 用中文城市名查智联 jl 码
export function zhCode(name) {
  const raw = String(name || '').trim();
  if (!raw) return '';
  if (ZH_MAP[raw] != null) return String(ZH_MAP[raw]);
  const n = strip(raw);
  if (ZH_MAP[n] != null) return String(ZH_MAP[n]);
  for (const [k, v] of Object.entries(ZH_MAP)) {
    if (k.includes('/') && k.split('/').includes(n)) return String(v);
    if (n.startsWith(k) || k.startsWith(n)) return String(v);
  }
  return '';
}

// 反查：jl 码 → 城市名
export function zhName(code) {
  const c = String(code || '');
  for (const [k, v] of Object.entries(ZH_MAP)) if (String(v) === c) return k;
  return '';
}
