/** 城市名 → dq 码；「全国」/空 → 410；未知城市返回 null（调用方可退回全国） */
export function lpDq(name) {
  const n = String(name || '').trim().replace(/市$/, '');
  if (!n || n === '全国' || n === '不限') return LP_NATIONWIDE_DQ;
  if (LP_DQ[n]) return LP_DQ[n];
  if (LP_PROV_DQ[n]) return LP_PROV_DQ[n];
  return null;
}
